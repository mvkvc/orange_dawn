defmodule OrangeDawn.Accounts do
  @moduledoc "Email accounts generated by phx.gen.auth, adapted for a JSON API."
  import Ecto.Query
  alias OrangeDawn.Accounts.{User, UserNotifier, UserToken}
  alias OrangeDawn.Repo

  def register_user(attrs) do
    %User{}
    |> User.email_changeset(attrs)
    |> Repo.insert()
  end

  def get_user_by_email(email), do: Repo.get_by(User, email: email)

  def create_user_api_token(user) do
    {encoded_token, user_token} = UserToken.build_email_token(user, "api-token")
    Repo.insert!(user_token)
    encoded_token
  end

  def fetch_user_by_api_token(token) do
    with {:ok, query} <- UserToken.verify_api_token_query(token),
         %User{} = user <- Repo.one(query) do
      {:ok, user}
    else
      _ -> :error
    end
  end

  def delete_user_api_token(token) do
    with {:ok, decoded} <- Base.url_decode64(token, padding: false) do
      hashed = :crypto.hash(:sha256, decoded)

      Repo.delete_all(
        from(t in UserToken, where: t.token == ^hashed and t.context == "api-token")
      )
    end

    :ok
  end

  def login_user_by_magic_link(token) do
    {:ok, query} = UserToken.verify_magic_link_token_query(token)

    Repo.transact(fn ->
      case Repo.one(lock(query, "FOR UPDATE")) do
        # Prevent session fixation attacks by disallowing magic links for unconfirmed users with password
        {%User{confirmed_at: nil, hashed_password: hash}, _token} when not is_nil(hash) ->
          raise """
          magic link log in is not allowed for unconfirmed users with a password set!

          This cannot happen with the default implementation, which indicates that you
          might have adapted the code to a different use case. Please make sure to read the
          "Mixing magic link and password registration" section of `mix help phx.gen.auth`.
          """

        {%User{confirmed_at: nil} = user, _token} ->
          user
          |> User.confirm_changeset()
          |> update_user_and_delete_all_tokens()

        {user, token} ->
          Repo.delete!(token)
          {:ok, {user, []}}

        nil ->
          {:error, :not_found}
      end
    end)
  end

  def deliver_login_instructions(%User{} = user, magic_link_url_fun)
      when is_function(magic_link_url_fun, 1) do
    {encoded_token, user_token} = UserToken.build_email_token(user, "login")
    Repo.insert!(user_token)
    UserNotifier.deliver_login_instructions(user, magic_link_url_fun.(encoded_token))
  end

  defp update_user_and_delete_all_tokens(changeset) do
    Repo.transact(fn ->
      with {:ok, user} <- Repo.update(changeset) do
        tokens_to_expire = Repo.all_by(UserToken, user_id: user.id)

        Repo.delete_all(from(t in UserToken, where: t.id in ^Enum.map(tokens_to_expire, & &1.id)))

        {:ok, {user, tokens_to_expire}}
      end
    end)
  end

  def generate_user_session_token(user) do
    {token, user_token} = UserToken.build_session_token(user)
    Repo.insert!(user_token)
    token
  end

  def get_user_by_session_token(token) do
    {:ok, query} = UserToken.verify_session_token_query(token)
    Repo.one(query)
  end

  def delete_user_session_token(token) do
    Repo.delete_all(from(t in UserToken, where: t.token == ^token and t.context == "session"))
    :ok
  end
end
